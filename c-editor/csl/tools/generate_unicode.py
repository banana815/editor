#!/usr/bin/env python3
"""Generate pinned Unicode 18 tables; no network access or product runtime.

Usage: python3 tools/generate_unicode.py path/to/ucd-18.0.0
Download exact URLs from data/unicode-sources.json into that directory first.
All input SHA-256 hashes are verified before generating anything.
"""
from pathlib import Path
import hashlib
import json
import sys

ROOT = Path(__file__).resolve().parents[1]
source = Path(sys.argv[1])
manifest = json.loads((ROOT / 'data/unicode-sources.json').read_text())
raw = {}
for item in manifest['files']:
    path = ROOT / 'data' / item['file'] if item['file'] == 'UNICODE-LICENSE.txt' else source / item['file']
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != item['sha256']:
        raise SystemExit('SHA-256 mismatch: ' + str(path))
    raw[item['file']] = data.decode('utf-8')

def rows(name):
    for line in raw[name].splitlines():
        body = line.partition('#')[0].strip()
        if body and not body.startswith('@'):
            yield [part.strip() for part in body.split(';')]

def seq(value):
    return [int(c, 16) for c in value.split()]

def array(values, count=3):
    assert len(values) <= count
    return '{' + ','.join('0x%Xu' % n for n in values + [0] * (count - len(values))) + '}'

banner = '/* Generated by tools/generate_unicode.py from pinned Unicode 18.0.0.\n * Copyright Unicode, Inc. See UNICODE-LICENSE.txt and unicode-sources.json. */\n'
out = [banner]
languages = {'': 0, 'tr': 1, 'az': 2, 'lt': 3}
contexts = {'': 0, 'Final_Sigma': 1, 'After_Soft_Dotted': 2,
            'More_Above': 3, 'Before_Dot': 4, 'Not_Before_Dot': 5, 'After_I': 6}
special = []
unconditional = {}
for row in rows('SpecialCasing.txt'):
    cp, lower, title, upper = int(row[0], 16), seq(row[1]), seq(row[2]), seq(row[3])
    condition = row[4].split() if len(row) > 4 else []
    lang, ctx = '', ''
    for token in condition:
        if token in languages:
            if lang: raise SystemExit('Multiple casing languages')
            lang = token
        elif token in contexts:
            if ctx: raise SystemExit('Multiple casing contexts')
            ctx = token
        else:
            raise SystemExit('Unimplemented casing condition: ' + token)
    special.append((cp, lower, title, upper, languages[lang], contexts[ctx]))
    if not condition: unconditional[cp] = (lower, title, upper)
special.sort(key=lambda r: (r[0], not (r[4] or r[5])))
out.append('static const SpecialCase special_cases[] = {\n')
for cp, lower, title, upper, lang, ctx in special:
    out.append(' {0x%Xu,%s,%s,%s,%d,%d,%d,%d,%d},\n' % (cp, array(lower), array(title), array(upper), len(lower), len(title), len(upper), lang, ctx))
out.append('};\n')

def properties(filename, wanted):
    ranges = {p: [] for p in wanted}
    for row in rows(filename):
        if row[1] not in ranges: continue
        limits = row[0].split('..')
        ranges[row[1]].append((int(limits[0], 16), int(limits[-1], 16)))
    for prop, values in ranges.items():
        merged = []
        for lo, hi in sorted(values):
            if merged and lo <= merged[-1][1] + 1:
                merged[-1] = (merged[-1][0], max(hi, merged[-1][1]))
            else: merged.append((lo, hi))
        out.append('static const CodepointRange %s_ranges[] = {\n' % prop.lower())
        out.extend(' {0x%Xu,0x%Xu},\n' % v for v in merged)
        out.append('};\n')

properties('DerivedCoreProperties.txt', ['Cased', 'Case_Ignorable'])
properties('PropList.txt', ['Soft_Dotted', 'White_Space'])
folds, turkic = {}, {}
for row in rows('CaseFolding.txt'):
    cp, status, mapping = int(row[0], 16), row[1], seq(row[2])
    if status in ('C', 'F'): folds[cp] = mapping
    if status == 'T': turkic[cp] = mapping
out.append('static const FoldCase turkic_folds[] = {\n')
for cp, mapping in sorted(turkic.items()):
    out.append(' {0x%Xu,%s,%d},\n' % (cp, array(mapping), len(mapping)))
out.append('};\n')
(ROOT / 'data/unicode-tables.inc').write_bytes(''.join(out).encode('utf-8'))

# Independent official expectations exercise utf8proc's simple/full mappings as
# well as our SpecialCasing overrides; contextual cases are hand-tested in C.
upper, lower, title = {}, {}, {}
for row in rows('UnicodeData.txt'):
    cp = int(row[0], 16)
    if row[12]: upper[cp] = seq(row[12])
    if row[13]: lower[cp] = seq(row[13])
    if row[14]: title[cp] = seq(row[14])
    elif row[12]: title[cp] = seq(row[12])
for cp, (lo, ti, up) in unconditional.items(): lower[cp], title[cp], upper[cp] = lo, ti, up
test = [banner]
for name, values in [('upper', upper), ('lower', lower), ('title', title), ('fold', folds), ('turkic', turkic)]:
    test.append('static const MappingFixture %s_fixtures[] = {\n' % name)
    for cp, mapping in sorted(values.items()):
        test.append(' {0x%Xu,%s,%d},\n' % (cp, array(mapping), len(mapping)))
    test.append('};\n')

normalization = [r[:5] for r in rows('NormalizationTest.txt')]
sample = [r for i, r in enumerate(normalization) if i < 64 or i % 127 == 0 or i >= len(normalization) - 32]
test.append('static const char *const normalization_fixtures[][5] = {\n')
for row in sample:
    strings = []
    for column in row:
        data = ''.join(chr(cp) for cp in seq(column)).encode('utf-8')
        strings.append('"' + ''.join('\\x%02x' % b for b in data) + '"')
    test.append(' {' + ','.join(strings) + '},\n')
test.append('};\n')
(ROOT / 'data/unicode-test-vectors.inc').write_bytes(''.join(test).encode('utf-8'))
print('Generated', len(special), 'special mappings;', len(upper), 'upper,', len(lower), 'lower,', len(title), 'title,', len(folds), 'fold and', len(sample), 'NFC fixtures')
