#!/usr/bin/env python3
"""Verify pinned CSL data and generate C arrays; used only during the build."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import tempfile
import xml.etree.ElementTree as ET


FILES = (
    ("apa.csl", "apa", "CE_CITATION_PROFILE_APA", "apa", "style"),
    ("ieee.csl", "ieee", "CE_CITATION_PROFILE_IEEE", "ieee", "style"),
    ("china-national-standard-gb-t-7714-2015-numeric.csl", "gbt",
     "CE_CITATION_PROFILE_GBT", "gbt-7714-2015-numeric", "style"),
    ("locales-en-US.xml", "en_us", None, None, "locale"),
    ("locales-zh-CN.xml", "zh_cn", None, None, "locale"),
)
CSL_NAMESPACE = "http://purl.org/net/xbiblio/csl"


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"duplicate manifest key: {key}")
        result[key] = value
    return result


def checked_bytes(directory, filename, record):
    data = (directory / filename).read_bytes()
    if not isinstance(record.get("bytes"), int) or len(data) != record["bytes"]:
        raise ValueError(f"{filename}: byte length does not match SOURCES.json")
    digest = record.get("sha256")
    if not isinstance(digest, str) or not re.fullmatch(r"[0-9a-f]{64}", digest):
        raise ValueError(f"{filename}: invalid SHA-256 in SOURCES.json")
    if hashlib.sha256(data).hexdigest() != digest:
        raise ValueError(f"{filename}: SHA-256 does not match SOURCES.json")
    if not data or len(data) > 2 * 1024 * 1024 or b"\0" in data:
        raise ValueError(f"{filename}: invalid resource size or embedded NUL")
    data.decode("utf-8", errors="strict")
    return data


def c_string(value):
    if not isinstance(value, str) or not value or "\0" in value:
        raise ValueError("invalid or empty resource metadata")
    # Short metadata strings only; all bytes escaped, independent of compiler
    # source encoding and without hex-escape lookahead ambiguity.
    data = value.encode("utf-8")
    if len(data) > 1024:
        raise ValueError("resource metadata exceeds 1024 bytes")
    return '"' + "".join(f"\\x{byte:02x}" for byte in data) + '"'


def verify_xml_metadata(filename, data, record, kind):
    root = ET.fromstring(data)
    if root.tag != f"{{{CSL_NAMESPACE}}}{kind}":
        raise ValueError(f"{filename}: wrong XML root or namespace")
    if root.get("version") != record.get("csl_version"):
        raise ValueError(f"{filename}: CSL version differs between XML and manifest")
    info = root.find(f"{{{CSL_NAMESPACE}}}info")
    fields = (("updated", "updated"), ("id", "id"), ("title", "title")) if kind == "style" else (("updated", "updated"),)
    for xml_name, key in fields:
        node = info.find(f"{{{CSL_NAMESPACE}}}{xml_name}") if info is not None else None
        value = node.text if node is not None else None
        if value is None or value != record.get(key):
            raise ValueError(f"{filename}: {key} differs between XML and manifest")
    if kind == "locale" and root.get("{http://www.w3.org/XML/1998/namespace}lang") != record.get("language"):
        raise ValueError(f"{filename}: locale language differs between XML and manifest")


def generate(directory):
    manifest = json.loads((directory / "SOURCES.json").read_text(encoding="utf-8"),
                          object_pairs_hook=unique_object)
    if not isinstance(manifest, dict) or manifest.get("format") != 1:
        raise ValueError("unsupported SOURCES.json format")
    resources = manifest.get("resources")
    if not isinstance(resources, list) or len(resources) != len(FILES):
        raise ValueError("SOURCES.json must list exactly the five pinned resources")
    by_name = {}
    for record in resources:
        if not isinstance(record, dict):
            raise ValueError("each resource record must be an object")
        name = record.get("file")
        if name in by_name:
            raise ValueError(f"duplicate resource: {name}")
        by_name[name] = record
    if set(by_name) != {row[0] for row in FILES}:
        raise ValueError("unexpected or missing pinned resource")
    license_record = manifest.get("license", {})
    if (not isinstance(license_record, dict) or license_record.get("file") != "LICENSE.txt" or
            license_record.get("spdx") != "CC-BY-SA-3.0"):
        raise ValueError("unexpected CSL resource license")
    checked_bytes(directory, "LICENSE.txt", license_record)
    lines = [
        "/* Generated by tools/embed_citation_styles.py; do not edit.",
        " * Data: Citation Style Language (CSL) project, https://citationstyles.org/.",
        " * These five unchanged XML byte arrays are CC-BY-SA-3.0 data.",
        " * Original individual credits remain inside the XML arrays.",
        " * Redistribute csl/resources/{README.md,SOURCES.json,LICENSE.txt}.",
        " * This data notice does not license the application/processor source. */",
    ]
    for filename, symbol, _, _, kind in FILES:
        record = by_name[filename]
        if record.get("kind") != kind or record.get("license") != "CC-BY-SA-3.0":
            raise ValueError(f"{filename}: wrong resource kind or license")
        if not re.fullmatch(r"[0-9a-f]{40}", record.get("commit", "")):
            raise ValueError(f"{filename}: invalid upstream commit")
        data = checked_bytes(directory, filename, record)
        verify_xml_metadata(filename, data, record, kind)
        lines.append(f"/* {filename}: SHA-256 {record['sha256']} */")
        lines.append(f"static const unsigned char citation_data_{symbol}[] = {{")
        # The last zero is a convenience sentinel, excluded from the XML size.
        data += b"\0"
        for offset in range(0, len(data), 16):
            lines.append("    " + ", ".join(f"0x{x:02x}" for x in data[offset:offset+16]) + ",")
        lines.append("};")
    locale_commit = by_name[FILES[3][0]]["commit"]
    if by_name[FILES[4][0]]["commit"] != locale_commit:
        raise ValueError("embedded locales must share a pinned upstream revision")
    lines.append("static const CeCitationStyleInfo citation_style_info[] = {")
    for filename, _, enum, profile_id, kind in FILES:
        if kind != "style":
            continue
        record = by_name[filename]
        fields = [profile_id, record["id"], record["title"], record["csl_version"],
                  record["updated"], record["commit"], record["sha256"], locale_commit]
        lines.append("    { " + enum + ", " + ", ".join(map(c_string, fields)) + " },")
    lines.append("};")
    return ("\n".join(lines) + "\n").encode("ascii")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--resources", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    try:
        generated = generate(args.resources)
        args.output.parent.mkdir(parents=True, exist_ok=True)
        if args.output.exists() and args.output.read_bytes() == generated:
            print("Verified five pinned CSL resources; generated data unchanged.")
            return
        temporary = None
        try:
            with tempfile.NamedTemporaryFile(dir=args.output.parent, prefix=args.output.name,
                                             suffix=".tmp", delete=False) as stream:
                temporary = Path(stream.name)
                stream.write(generated)
            os.replace(temporary, args.output)
            temporary = None
        finally:
            if temporary is not None:
                temporary.unlink(missing_ok=True)
        print("Verified five pinned CSL resources and license; generated C byte arrays.")
    except (OSError, ValueError, KeyError, TypeError, ET.ParseError) as error:
        parser.exit(1, f"CSL resource generation failed: {error}\n")


if __name__ == "__main__":
    main()
